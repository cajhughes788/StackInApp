function normalizeIndianaCountyKey(value?: string): string {
  return (value ?? "")
    .trim()
    .replace(/\bcounty\b/gi, "")
    .replace(/\s+/g, " ")
    .replace(/^saint\s+/i, "St. ")
}

export function getIndianaCountyTaxRate(county?: string): number | null {
  const normalized = normalizeIndianaCountyKey(county)
  return normalized ? INDIANA_COUNTY_TAX_RATES_2026[normalized] ?? null : null
}
